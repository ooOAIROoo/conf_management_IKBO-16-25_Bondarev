def glyph(char: str):
    """Возвращает сетку знака или заглушку."""
    return GLYPHS.get(char.upper(), _UNKNOWN)


def advance(scale: int) -> int:
    """Ширина шага курсора для одного знака."""
    return (GLYPH_WIDTH + SPACING) * scale


def text_width(text: str, scale: int) -> int:
    """Ширина строки в пикселях."""
    if not text:
        return 0
    return len(text) * advance(scale) - SPACING * scale


def max_chars(width: int, scale: int) -> int:
    """Сколько знаков помещается в ширину."""
    step = advance(scale)
    if step <= 0:
        return 0
    return max(width // step, 1)


def fit(text: str, width: int, scale: int) -> str:
    """Обрезает текст под ширину, ставя «..»."""
    limit = max_chars(width, scale)
    if len(text) <= limit:
        return text
    if limit <= 2:
        return text[:limit]
    return text[:limit - 2] + ".."
